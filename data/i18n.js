// Helper: resolve a field with EN fallback to KO
window.pickLang = function(obj, key, lang) {
  if (!obj) return '';
  if (lang === 'en') {
    const enKey = key + 'En';
    if (obj[enKey]) return obj[enKey];
  }
  return obj[key] || '';
};
